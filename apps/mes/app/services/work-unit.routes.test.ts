const op = "op_2";
const caller = { companyId: "co", userId: "user" };

/** A serial part with units u1 (done here), u2 and u3 open. */
function floor({
  later = true,
  allDone = false,
  firstDone = true,
  extra = {}
}: {
  later?: boolean;
  allDone?: boolean;
  firstDone?: boolean;
  extra?: Record<string, Record<string, unknown>[]>;
} = {}) {
  return fakeClient({
    ...extra,
    jobOperation: [serialOperation({ id: op, jobMakeMethodId: "jmm", later })],
    jobMakeMethod: [
      {
        id: "jmm",
        companyId: "co",
        requiresSerialTracking: true,
        requiresBatchTracking: false
      }
    ],
    job: [{ id: "job", companyId: "co", status: "In Progress" }],
    jobOperationStep: [{ id: "step", companyId: "co", operationId: op }],
    trackedEntity: serialUnits("jmm", op, [
      { id: "u1", done: firstDone },
      { id: "u2", done: allDone },
      { id: "u3", done: allDone }
    ])
  });
}

/** The toast a response's flash cookie carries. */
async function toast(response: unknown) {
  const init = (response as { init?: { headers?: Record<string, string> } })
    .init;
  const cookie = init?.headers?.["Set-Cookie"]?.split(";")[0] ?? "";
  const flash = await getSessionFlash(
    new Request("http://mes.test", { headers: { Cookie: cookie } })
  );
  return flash?.result.message;
}

/**
 * The reads up to the unit check: the operation, its unit rule, its units,
 * and whether the company holds units with an open quality issue.
 */
const GATE_READS = [
  "jobOperation",
  "jobOperation",
  "trackedEntity",
  "jobOperationTrackedEntity",
  "trackedActivityOutput",
  "jobReceivedSerial",
  "companySettings"
];

/** Unit `unitId` has an open quality issue, and the company holds such units. */
const onHold = (unitId: string, disposition?: string) => ({
  companySettings: [{ id: "co", holdUnitsWithOpenIssues: true }],
  unitQualityHold: [
    {
      trackedEntityId: unitId,
      companyId: "co",
      issueId: "nc_1",
      issueNumber: "NCR-1",
      name: "Cracked housing",
      description: null,
      status: disposition ? "Closed" : "Registered",
      disposition,
      createdAt: "2026-01-01T00:00:00Z",
      issueType: "Defect"
    }
  ]
});

const get = (path: string) => new Request(`http://mes.test${path}`);
const post = (path: string, fields: Record<string, string>) => {
  const body = new FormData();
  for (const [key, value] of Object.entries(fields)) body.set(key, value);
  return new Request(`http://mes.test${path}`, { method: "POST", body });
};
const location = (response: unknown) =>
  (response as Response).headers.get("Location");

describe("kanban Complete scan (end route)", () => {
  it("asks for the unit instead of completing one nobody picked", async () => {
    const fake = floor();
    const response = await endOperationByScan(fake, {
      ...caller,
      request: get(`/x/end/${op}`),
      operationId: op
    });
    expect(location(response)).toBe(`/x/operation/${op}`);
    expect(fake.writes()).toEqual([]);
  });

  it("completes the unit the screen held", async () => {
    const fake = floor();
    await endOperationByScan(fake, {
      ...caller,
      request: get(`/x/end/${op}?trackedEntityId=u3`),
      operationId: op
    });
    expect(fake.posts).toEqual([
      {
        name: "issue",
        input: {
          type: "jobOperationSerialComplete",
          quantity: 1,
          jobOperationId: op,
          trackedEntityId: "u3",
          notes: "Generated by QR code"
        }
      }
    ]);
  });

  it("completes the next unit in order on the first operation", async () => {
    const fake = floor({ later: false });
    await endOperationByScan(fake, {
      ...caller,
      request: get(`/x/end/${op}`),
      operationId: op
    });
    expect(fake.posts.map((p) => p.input.trackedEntityId)).toEqual(["u2"]);
  });

  it.each(["Complete", "Produce"])(
    "skips a serial credited only by a prior %s when the QR names no unit",
    async (type) => {
      const fake = floor({
        later: false,
        firstDone: false,
        extra: {
          trackedActivityOutput: [
            operationOutput("u1", op, type),
            operationOutput("u2", "other-op", "Produce"),
            operationOutput("u2", op, "Unconsume")
          ]
        }
      });
      await endOperationByScan(fake, {
        ...caller,
        request: get(`/x/end/${op}`),
        operationId: op
      });
      expect(fake.posts.map((post) => post.input.trackedEntityId)).toEqual([
        "u2"
      ]);
    }
  );

  it("completes nothing for a unit on hold for an open quality issue", async () => {
    const fake = floor({ extra: onHold("u3") });
    const response = await endOperationByScan(fake, {
      ...caller,
      request: get(`/x/end/${op}?trackedEntityId=u3`),
      operationId: op
    });
    expect(location(response)).toBe(`/x/operation/${op}?trackedEntityId=u3`);
    expect(fake.writes()).toEqual([]);
  });

  it("skips a unit on hold for the next unit on the first operation", async () => {
    const fake = floor({ later: false, extra: onHold("u2") });
    await endOperationByScan(fake, {
      ...caller,
      request: get(`/x/end/${op}`),
      operationId: op
    });
    expect(fake.posts.map((p) => p.input.trackedEntityId)).toEqual(["u3"]);
  });
});

