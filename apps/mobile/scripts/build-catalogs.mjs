/**
 * Generate `src/i18n/generated/<locale>.ts` from the shared MES Lingui catalogs.
 *
 * WHY THIS EXISTS instead of `@lingui/metro-transformer`:
 * that transformer compiles `.po` files on the fly by setting
 * `transformer.babelTransformerPath`, and Uniwind's Metro integration wraps the
 * transform pipeline too. Rather than chain two transformers through one slot,
 * the catalogs are compiled ahead of time by the repo's own
 * `pnpm run lingui:compile` (already a turbo build step) and inlined as plain
 * TypeScript. Metro then needs no custom transformer and no `.po` resolution,
 * and `tsc` typechecks the catalogs like any other module.
 *
 * The output is gitignored and rebuilt by `prestart` and `typecheck`, so it can
 * never drift from the `.po` files that ARE committed.
 */
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = join(here, "..");
const repoRoot = join(appRoot, "../..");
const localesDir = join(repoRoot, "packages/locale/locales");
const outDir = join(appRoot, "src/i18n/generated");

/** Read the locale list from lingui.config.js without loading @lingui/cli. */
function linguiLocales() {
  const source = readFileSync(join(repoRoot, "lingui.config.js"), "utf8");
  const match = source.match(/locales:\s*\[([^\]]*)\]/);
  if (!match) throw new Error("lingui.config.js has no `locales:` array");
  return [...match[1].matchAll(/"([a-z-]+)"/g)].map((m) => m[1]);
}

const locales = linguiLocales();

function poPath(locale) {
  return join(localesDir, locale, "mes.po");
}
function compiledPath(locale) {
  return join(localesDir, locale, "mes.mjs");
}

/** A `.po` newer than its compiled `.mjs` means the catalog moved on. */
function needsCompile() {
  return locales.some((locale) => {
    const compiled = compiledPath(locale);
    if (!existsSync(compiled)) return true;
    const po = poPath(locale);
    if (!existsSync(po)) return true;
    return statSync(po).mtimeMs > statSync(compiled).mtimeMs;
  });
}

if (needsCompile()) {
  // `lingui compile --namespace es` writes packages/locale/locales/*/mes.mjs.
  // Those files are gitignored build artifacts, exactly as the web apps treat them.
  execFileSync("pnpm", ["run", "lingui:compile"], {
    cwd: repoRoot,
    stdio: "inherit"
  });
}

mkdirSync(outDir, { recursive: true });

const header = `// SPDX-License-Identifier: AGPL-3.0-only
// Carbon (github.com/crbnos/carbon). Modified or adapted versions of this file,
// including ports, remain AGPLv3; serving them over a network requires releasing their source.

// @generated by scripts/build-catalogs.mjs from packages/locale/locales/*/mes.po
// DO NOT EDIT. Run \`pnpm run catalogs\` to refresh.
`;

let written = 0;
for (const locale of locales) {
  const compiled = compiledPath(locale);
  if (!existsSync(compiled)) {
    throw new Error(
      `Missing compiled catalog ${compiled}. Run \`pnpm run lingui:compile\` at the repo root.`
    );
  }
  const { messages } = await import(`file://${compiled}`);
  writeFileSync(
    join(outDir, `${locale}.ts`),
    `${header}
import type { Messages } from "@lingui/core";

export const messages: Messages = ${JSON.stringify(messages, null, 0)} as Messages;
`,
    "utf8"
  );
  written++;
}

writeFileSync(
  join(outDir, "index.ts"),
  `${header}
import type { Messages } from "@lingui/core";
${locales.map((l) => `import { messages as ${l.replace(/-/g, "_")} } from "./${l}";`).join("\n")}

/**
 * Every shipped locale's messages. React Native builds ONE bundle, so a lazy
 * import would not keep these out of it — a static map is simpler and lets
 * \`tsc\` prove the set matches MES_LOCALES.
 */
export const catalogs: Record<string, Messages> = {
${locales.map((l) => `  "${l}": ${l.replace(/-/g, "_")}`).join(",\n")}
};
`,
  "utf8"
);

console.log(`build-catalogs: wrote ${written} locale(s) + index to src/i18n/generated`);
