import {
  type DocumentTemplate,
  isFigureProblem
} from "@carbon/documents/template";
import { getLogger } from "@carbon/logger";
import { Spinner } from "@carbon/react";
import { Trans } from "@lingui/react/macro";
import { lazy, Suspense, useEffect, useRef, useState } from "react";
import {
  changedNotes,
  draftProblems,
  useDocumentTemplate,
  useEditorStore
} from "./context";
import { type PageClick, resolveClick } from "./previewClick";
import { fillPrintedTexts, printedTexts } from "./previewText";

const PreviewPages = lazy(() => import("./PreviewPages"));

const logger = getLogger("erp", "templatepreview");

const PREVIEW_DEBOUNCE_MS = 500;

/**
 * Server-rendered preview. The PDF is generated by the `.preview` route (Node,
 * where @react-pdf/renderer's Buffer/stream deps exist), so it is
 * byte-identical to the real document route. It is drawn with pdf.js rather
 * than the browser's own viewer because a click on a word must reach the
 * editor: it selects the block that prints the word and points its panel at it.
 */
export function TemplatePreview({ previewPath }: { previewPath: string }) {
  const {
    blocks,
    sections,
    theme,
    settings,
    headerSectionId,
    footerSectionId,
    headerConfig,
    previewId
  } = useDocumentTemplate();
  const documentType = useEditorStore((s) => s.documentType);
  const document = useEditorStore((s) => s.document);
  const focusText = useEditorStore((s) => s.focusText);
  const pointedAtPage = useEditorStore((s) => s.textFocus?.fromPage === true);
  const documentValues = useEditorStore((s) => s.documentValues);
  const notes = useEditorStore(changedNotes);
  const previewNonce = useEditorStore((s) => s.previewNonce);
  const labelSizeId = useEditorStore((s) => s.labelSizeId);
  const [url, setUrl] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [notice, setNotice] = useState<"failed" | "figure" | null>(null);
  // A locked value is no text the panel can show.
  const textToChange =
    notice === "figure"
      ? draftProblems({ documentType, document, blocks, settings }).find(
          (problem) =>
            isFigureProblem(problem) && problem.code !== "valueLocked"
        )
      : undefined;
  // What each PDF was drawn from: the shown one can be older than the draft.
  const drawnFrom = useRef(
    new Map<string, Pick<DocumentTemplate, "blocks" | "settings">>()
  );

  // biome-ignore lint/correctness/useExhaustiveDependencies: `previewNonce` is a manual retrigger — bumped by the toolbar refresh button to re-run the fetch.
  useEffect(() => {
    const controller = new AbortController();
    const handle = setTimeout(async () => {
      // No figure the record does not say reaches a PDF; the field shows why. A
      // locked record prints what it saved, whatever the draft says.
      if (
        !document?.locked &&
        draftProblems({ documentType, document, blocks, settings }).some(
          isFigureProblem
        )
      ) {
        setIsLoading(false);
        setNotice("figure");
        return;
      }
      setNotice(null);
      setIsLoading(true);
      try {
        const formData = new FormData();
        formData.append("blocks", JSON.stringify(blocks));
        formData.append("theme", JSON.stringify(theme));
        formData.append("settings", JSON.stringify(settings));
        formData.append("headerSectionId", headerSectionId ?? "");
        formData.append("footerSectionId", footerSectionId ?? "");
        formData.append("headerConfig", JSON.stringify(headerConfig));
        formData.append("labelSizeId", labelSizeId);
        if (previewId) formData.append("previewId", previewId);
        if (notes !== undefined) formData.append("notes", notes);
        const response = await fetch(previewPath, {
          method: "post",
          body: formData,
          signal: controller.signal
        });
        if (!response.ok) {
          setNotice("failed");
          logger.error("The preview could not be rendered", {
            status: response.status
          });
          return;
        }
        const blob = await response.blob();
        const nextUrl = URL.createObjectURL(blob);
        drawnFrom.current.set(nextUrl, { blocks, settings });
        setUrl(nextUrl);
      } catch (error) {
        if (!controller.signal.aborted) {
          setNotice("failed");
          logger.error("Error", { error: error });
        }
      } finally {
        if (!controller.signal.aborted) setIsLoading(false);
      }
    }, PREVIEW_DEBOUNCE_MS);

    return () => {
      controller.abort();
      clearTimeout(handle);
    };
    // `headerConfig` is a dep so logo/header edits (sent in the payload and
    // applied server-side) retrigger a fresh render without a save round-trip.
  }, [
    blocks,
    theme,
    settings,
    headerSectionId,
    footerSectionId,
    headerConfig,
    previewId,
    previewPath,
    previewNonce,
    labelSizeId,
    documentType,
    document,
    notes
  ]);

  useEffect(() => {
    const urls = drawnFrom.current;
    return () => {
      for (const url of urls.keys()) URL.revokeObjectURL(url);
    };
  }, []);

  // The file on screen and the newest stay; any in between never showed. Read the
  // newest from the map: this runs from a draw that started before it arrived.
  const onShown = (shown: string) => {
    setNotice((current) => (current === "failed" ? null : current));
    const newest = [...drawnFrom.current.keys()].at(-1);
    for (const drawn of drawnFrom.current.keys()) {
      if (drawn !== shown && drawn !== newest) {
        URL.revokeObjectURL(drawn);
        drawnFrom.current.delete(drawn);
      }
    }
  };

  const onTextClick = (click: PageClick) => {
    const drawn = drawnFrom.current.get(click.file);
    if (!drawn) return false;
    const words = printedTexts(documentType, drawn.blocks, drawn.settings, {
      content: (id) => sections.find((section) => section.id === id)?.content,
      headerSectionId,
      footerSectionId
    });
    const hit = resolveClick(
      click,
      documentType,
      documentValues
        ? fillPrintedTexts(words, documentValues, drawn.settings.valueEdits)
        : words
    );
    if (hit) focusText(hit.scope, hit.key, hit.exact);
    return hit?.exact ?? false;
  };

  return (
    <div className="relative mx-auto flex h-full w-full max-w-3xl flex-col overflow-hidden">
      {notice && !isLoading && (
        <p className="mb-2 shrink-0 rounded-md bg-destructive/10 px-3 py-2 text-sm text-destructive">
          {notice === "figure" ? (
            <>
              <Trans>
                This preview is paused because a text changes a figure.
              </Trans>
              {textToChange && (
                <>
                  {" "}
                  <Trans>
                    Please{" "}
                    <button
                      type="button"
                      className="font-medium underline underline-offset-2"
                      onClick={() =>
                        focusText(
                          textToChange.blockId,
                          textToChange.field,
                          false,
                          true
                        )
                      }
                    >
                      change it
                    </button>
                    .
                  </Trans>
                </>
              )}
            </>
          ) : (
            <Trans>
              The preview could not be drawn. It shows the last one that was.
            </Trans>
          )}
        </p>
      )}
      {url && (
        <div className="min-h-0 flex-1">
          <Suspense fallback={null}>
            <PreviewPages
              file={url}
              onTextClick={onTextClick}
              onDrawFailed={() => setNotice("failed")}
              onShown={onShown}
              keepMark={pointedAtPage}
            />
          </Suspense>
        </div>
      )}
      {isLoading && (
        <div className="absolute inset-0 flex items-center justify-center bg-background/60 backdrop-blur-[1px]">
          <Spinner className="size-6" />
        </div>
      )}
    </div>
  );
}
