/** Turns a merge field's or group's English name into the reader's language. */
export function useMergeFieldName() {
  const { i18n } = useLingui();
  return useCallback(
    (name: string) => {
      const descriptor = MERGE_FIELD_NAMES[name];
      return descriptor ? i18n._(descriptor) : name;
    },
    [i18n]
  );
}
