export function validateDatabaseUrl(value: string | undefined): string {
  if (!value?.trim()) {
    throw new Error(
      "SUPABASE_DB_URL is not set. Configure the local database before generating types."
    );
  }
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    throw new Error("SUPABASE_DB_URL must be a valid local PostgreSQL URL.");
  }
  if (
    !["postgres:", "postgresql:"].includes(url.protocol) ||
    !["localhost", "127.0.0.1", "[::1]"].includes(url.hostname) ||
    url.searchParams.has("host") ||
    url.searchParams.has("hostaddr")
  ) {
    // Never include the URL: even a redacted password can leave private hosts,
    // usernames or query parameters in output copied into public run logs.
    throw new Error(
      "Refusing to generate types: SUPABASE_DB_URL must use a local PostgreSQL host."
    );
  }
  return value;
}

// Strip per-tenant `searchIndex_<companyId>` / `auditLog_<companyId>` tables.
// They are created at runtime per company, so which ones exist depends on the
// local DB's seeded companies — committing them makes types.ts
// machine-dependent. The static `searchIndexRegistry` / `auditLogArchive`
// tables (no underscore) are unaffected.
export function stripPerTenantTables(source: string): string {
  const lines: string[] = [];
  let skipping = false;
  for (const line of source.split("\n")) {
    if (
      !skipping &&
      /^      "?(searchIndex|auditLog)_[A-Za-z0-9-]+"?: \{$/.test(line)
    ) {
      skipping = true;
      continue;
    }
    if (skipping) {
      if (line === "      }") skipping = false;
      continue;
    }
    lines.push(line);
  }
  return lines.join("\n");
}

// `supabase gen types` emits a table's `Relationships` entries in catalog order,
// which is not stable across databases built from the same migrations (two
// foreign keys to the same table swap places between runs). Sort each block's
// entries by their text so the output is a pure function of the schema and the
// generated-files drift check can compare it byte for byte.
export function sortRelationships(source: string): string {
  const lines = source.split("\n");
  const out: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? "";
    out.push(line);
    if (!/^\s*Relationships: \[$/.test(line)) continue;
    const indent = line.match(/^\s*/)?.[0] ?? "";
    const entries: string[][] = [];
    let j = i + 1;
    while (j < lines.length && lines[j] !== `${indent}]`) {
      if (lines[j] === `${indent}  {`) {
        const entry = [lines[j] ?? ""];
        j++;
        while (j < lines.length && !/^\s*\},?$/.test(lines[j] ?? ""))
          entry.push(lines[j++] ?? "");
        entry.push(lines[j] ?? "");
        entries.push(entry);
      }
      j++;
    }
    if (j >= lines.length) continue;
    const closing = lines[j] ?? "";
    entries.sort((a, b) => {
      const ka = a.slice(1, -1).join("\n");
      const kb = b.slice(1, -1).join("\n");
      return ka < kb ? -1 : ka > kb ? 1 : 0;
    });
    entries.forEach((entry, index) => {
      const last = (entry[entry.length - 1] ?? "").replace(/,$/, "");
      out.push(
        ...entry.slice(0, -1),
        index < entries.length - 1 ? `${last},` : last
      );
    });
    out.push(closing);
    i = j;
  }
  return out.join("\n");
}

const CONSTANTS_START = "export const Constants = {";

/** Header of the generated `constants.ts` (the file has no license header). */
export const CONSTANTS_HEADER = [
  "// Generated by `pnpm run generate:types` (scripts/lib/generate-db-types.ts)",
  "// from the `Constants` block of `supabase gen types`. Do not edit.",
  "//",
  "// It is the only runtime value in the generated types, so it lives apart from",
  "// `types.ts`: a browser that needs an enum's values then loads this file, not",
  "// the 3 MB of type declarations beside it (the dev server serves every module",
  "// whole, with its sourcemap).",
  ""
].join("\n");

/**
 * Splits the generated source into `types.ts` (declarations only) and
 * `constants.ts` (the `Constants` object). Throws when the block is missing,
 * so a change in the CLI's output fails the run rather than dropping every
 * enum's runtime values.
 */
export function splitConstants(source: string): {
  types: string;
  constants: string;
} {
  const start = source.indexOf(CONSTANTS_START);
  if (start < 0) {
    throw new Error(
      "Database type generation produced no Constants block; the existing type files were preserved."
    );
  }
  return {
    types: `${source.slice(0, start).trimEnd()}\n`,
    constants: `${CONSTANTS_HEADER}${source.slice(start).trimEnd()}\n`
  };
}

/**
 * The tail of the CLI's stderr, for the error message. The CLI echoes the
 * `--db-url` on some failures, so every PostgreSQL URL is replaced before the
 * text leaves this function; a run log must never carry the password.
 */
export function describeFailure(
  result: { error?: Error; stderr?: Buffer | string | null },
  dbUrl: string
): string {
  if (result.error) return ` ${result.error.message}`;
  const text = (result.stderr ?? "").toString().trim();
  if (!text) return "";
  const redacted = text
    .split(dbUrl)
    .join("<db-url>")
    .replace(/postgres(ql)?:\/\/[^\s"']+/g, "<db-url>");
  const lines = redacted.split("\n");
  const tail = lines.slice(-12).join("\n");
  return `\n${lines.length > 12 ? "…\n" : ""}${tail}`;
}

export async function generateDatabaseTypes(
  databaseUrl: string | undefined
): Promise<void> {
  const dbUrl = validateDatabaseUrl(databaseUrl);
  const target = resolve("packages/database/src/types.ts");
  const constantsTarget = resolve("packages/database/src/constants.ts");
  const directory = mkdtempSync(join(dirname(target), ".db-types-"));
  try {
    const candidate = join(directory, "types.ts");
    const out = openSync(candidate, "wx");
    try {
      // File-backed stdout avoids truncating large schemas or a maxBuffer cap.
      // Do not inherit stderr: CLI failures can echo the credential-bearing URL.
      const result = spawnSync(
        "supabase",
        [
          "gen",
          "types",
          "typescript",
          "--db-url",
          dbUrl,
          "--schema",
          "public",
          "--schema",
          "storage",
          "--schema",
          "graphql_public"
        ],
        {
          stdio: ["ignore", out, "pipe"],
          // The CLI runs `postgres-meta` in a container it pulls from AWS ECR
          // by default, whose blob downloads redirect to CloudFront. A Claude
          // cloud container's proxy denies CloudFront, so there (only) pull the
          // same image from Docker Hub.
          env:
            process.env.CARBON_DEV_CLOUD === "1"
              ? { SUPABASE_INTERNAL_IMAGE_REGISTRY: "docker.io", ...process.env }
              : process.env
        }
      );
      if (result.error || result.status !== 0) {
        const status =
          result.status === null
            ? "could not complete"
            : `exited ${result.status}`;
        const detail = describeFailure(result, dbUrl);
        throw new Error(
          `Supabase type generation ${status}; the existing type file was preserved.${detail}`
        );
      }
    } finally {
      closeSync(out);
    }
    const normalized = sortRelationships(
      stripPerTenantTables(readFileSync(candidate, "utf8"))
    );
    if (!/^export type Database\b/m.test(normalized)) {
      throw new Error(
        "Database type generation did not produce an exported Database type; the existing type file was preserved."
      );
    }
    const { types, constants } = splitConstants(normalized);
    // The company-table list is read from the staged types, so a short list
    // fails before anything is published and all three files land together.
    __setDbTypesContentForTest(`${types}\n${constants}`);
    const companyTables = renderCompanyTables(
      getDbTablesWithColumn("companyId")
    );
    const rowSchemas = renderRowSchemas(await rowRelations());
    const staged = join(directory, "staged.ts");
    const stagedConstants = join(directory, "staged-constants.ts");
    const stagedCompanyTables = join(directory, "staged-company-tables.ts");
    const stagedRows = join(directory, "staged-row-schemas.ts");
    writeFileSync(staged, types);
    writeFileSync(stagedConstants, constants);
    writeFileSync(stagedCompanyTables, companyTables);
    writeFileSync(stagedRows, rowSchemas);
    renameSync(stagedConstants, constantsTarget);
    renameSync(staged, target);
    renameSync(
      stagedCompanyTables,
      resolve("packages/database/src/company-tables.ts")
    );
    renameSync(stagedRows, resolve("packages/database/src/row-schemas.ts"));
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

/**
 * The tables a tenant's rows live in, as a committed module: the API's
 * dispatcher confines every update and delete on one of them to the caller's
 * company (`scopedToCompany`). Generated here, beside the types it is read
 * from, so the list can never be empty or stale at runtime.
 */
export function renderCompanyTables(tables: string[]): string {
  if (!tables.includes("customer") || tables.length < 100) {
    throw new Error(
      `generate:types found only ${tables.length} tables with a companyId column; the company filter depends on that list. Nothing was written.`
    );
  }
  return [
    "// Generated by `pnpm run generate:types` (scripts/lib/generate-db-types.ts)",
    "// from the generated database types. Do not edit.",
    "",
    "/** Every `public` table with a `companyId` column, sorted. */",
    "export const COMPANY_TABLES: readonly string[] = [",
    // No trailing comma: the file is committed as Biome formats it
    // (`trailingCommas: "none"`), and CI diffs it against a fresh render.
    tables.map((table) => `  ${JSON.stringify(table)}`).join(",\n"),
    "] as const;",
    ""
  ].join("\n");
}

/** A public table or view with the columns of its `Row`, and the table its `id` is. */
export type RowRelation = {
  name: string;
  kind: "table" | "view";
  /** The table whose `id` the relation's `id` is: itself for a table; for a view, the base table, or nothing when its id is computed. */
  table?: string;
  fields: DbTableField[];
};

/** Every public table and view of the generated types, with each view's base table from the migrations. */
export async function rowRelations(): Promise<RowRelation[]> {
  const tables = getDbRelationNames("Tables");
  const views = getDbRelationNames("Views");
  const bases = await viewBaseTables(tables, views);
  const relations: RowRelation[] = [];
  for (const name of [...tables].sort()) {
    const fields = getDbTableTypeFields(name, "Row");
    if (fields) relations.push({ name, kind: "table", table: name, fields });
  }
  for (const name of [...views].sort()) {
    const fields = getDbTableTypeFields(name, "Row");
    if (fields) {
      relations.push({ name, kind: "view", table: bases.get(name)?.table, fields });
    }
  }
  return relations;
}

const ENUM_REF = /^Database\["public"\]\["Enums"\]\["(\w+)"\]$/;

/**
 * The zod expression for one generated column type: `string | null` →
 * `z.string().nullable()`, `Database["public"]["Enums"]["x"][]` →
 * `z.array(enums.x)`. `Json` and anything unrecognised are `z.unknown()`.
 */
export function zodExpressionFor(typeStr: string): string {
  const members = typeStr.split("|").map((m) => m.trim()).filter(Boolean);
  const nullable = members.includes("null");
  const rest = members.filter((m) => m !== "null");
  const base = rest.length === 1 ? rest[0]! : "unknown";
  const expr = (() => {
    if (base.endsWith("[]")) {
      const inner = zodExpressionFor(base.slice(0, -2));
      return `z.array(${inner})`;
    }
    const enumRef = ENUM_REF.exec(base);
    if (enumRef) return `enums.${enumRef[1]}`;
    switch (base) {
      case "string":
        return "z.string()";
      case "number":
        return "z.number()";
      case "boolean":
        return "z.boolean()";
      default:
        return "z.unknown()";
    }
  })();
  return nullable ? `${expr}.nullable()` : expr;
}

/**
 * `packages/database/src/row-schemas.ts`: one zod object per public table and view,
 * the row the API returns, for a service function's declared `output`. Each
 * carries `meta({ table })` — the table its `id` is — so the catalog can tell
 * which list reads return a table's ids. Generated beside the types so it can
 * never disagree with them.
 */
export function renderRowSchemas(relations: RowRelation[]): string {
  const enumNames = new Set<string>();
  for (const relation of relations) {
    for (const field of relation.fields) {
      for (const m of field.typeStr.matchAll(/Database\["public"\]\["Enums"\]\["(\w+)"\]/g)) {
        enumNames.add(m[1]!);
      }
    }
  }
  const enumLines: string[] = [];
  for (const name of [...enumNames].sort()) {
    const values = getDbEnumValues(name);
    if (!values) throw new Error(`generate:types found no values for enum ${name}`);
    enumLines.push(`  ${name}: z.enum(${JSON.stringify(values)}),`);
  }
  const relationLines: string[] = [];
  for (const relation of relations) {
    const columns = relation.fields
      .map((f) => `    ${JSON.stringify(f.name)}: ${zodExpressionFor(f.typeStr)},`)
      .join("\n");
    const meta =
      relation.kind === "table"
        ? `{ table: ${JSON.stringify(relation.name)} }`
        : relation.table
          ? `{ table: ${JSON.stringify(relation.table)}, view: ${JSON.stringify(relation.name)} }`
          : `{ view: ${JSON.stringify(relation.name)} }`;
    relationLines.push(
      `  ${JSON.stringify(relation.name)}: z.object({\n${columns}\n  }).meta(${meta}),`
    );
  }
  return [
    "// Generated by `pnpm run generate:types` (scripts/lib/generate-db-types.ts)",
    "// from the generated database types. Do not edit.",
    "",
    'import { z } from "zod";',
    "",
    "/** The `public` enums, by name. */",
    "export const enums = {",
    ...enumLines,
    "} as const;",
    "",
    "/**",
    " * The row of each `public` table and view, as the API returns it: a service",
    " * function's `output` is one of these, an array of one, a `.pick()` of one or",
    " * one `.extend()`ed. `meta.table` is the table the row's `id` belongs to (a",
    " * view's base table; absent when the view's id is computed), which is how the",
    " * catalog finds the list reads that return a table's ids.",
    " */",
    "export const rows = {",
    ...relationLines,
    "} as const;",
    "",
    "export type Rows = typeof rows;",
    ""
  ].join("\n");
}
