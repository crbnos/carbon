import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import type { SourceFile } from "../check";

const MIGRATIONS_REL = "packages/database/supabase/migrations";

/**
 * Repo root, resolved from this source file (not cwd) so checks run correctly
 * from any working directory. This file is packages/checks/src/sources/ → 4 up.
 */
export function repoRoot(): string {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
  if (!existsSync(join(root, MIGRATIONS_REL))) {
    throw new Error(
      `Could not locate repo root from ${import.meta.url} (resolved ${root}); ${MIGRATIONS_REL} not found.`
    );
  }
  return root;
}

/**
 * The first line of a migration rendered from the manifest by `authz migration` — the WHOLE
 * line, equal to GENERATED_HEADER in packages/database/src/authz/migration.ts (pinned by the
 * no-authz-ddl-in-migrations test). Those files carry policy and helper DDL on purpose, and
 * @carbon/database's migration.test.ts verifies the contents of exactly the files that start
 * with that full line. Matching only a prefix let a hand-written file with an edited suffix
 * skip both.
 */
export const GENERATED_AUTHZ_MIGRATION =
  "-- Generated by `pnpm --filter @carbon/database authz migration` from packages/database/src/authz. Do not edit.";

export function migrationsDir(root: string): string {
  return join(root, MIGRATIONS_REL);
}

export function loadSqlFiles(dir: string): SourceFile[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((f) => ({ file: f, contents: readFileSync(join(dir, f), "utf8") }));
}
