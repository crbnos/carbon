describe("applyLicenseHeader", () => {
  it("puts the header first, then exactly one blank line", () => {
    expect(applyLicenseHeader('import a from "a";\n', "agpl")).toBe(
      `${AGPL}\n\nimport a from "a";\n`
    );
    expect(applyLicenseHeader("\n\n\nexport {};\n", "commercial")).toBe(
      `${COMMERCIAL}\n\nexport {};\n`
    );
  });

  it("keeps a shebang on line 1", () => {
    expect(
      applyLicenseHeader("#!/usr/bin/env node\nconsole.log(1);\n", "agpl")
    ).toBe(`#!/usr/bin/env node\n${AGPL}\n\nconsole.log(1);\n`);
    expect(
      applyLicenseHeader("#!/usr/bin/env node\n\nconsole.log(1);\n", "agpl")
    ).toBe(`#!/usr/bin/env node\n${AGPL}\n\nconsole.log(1);\n`);
  });

  it('goes above "use client" / "use server" directives', () => {
    expect(applyLicenseHeader('"use client";\n\nexport {};\n', "agpl")).toBe(
      `${AGPL}\n\n"use client";\n\nexport {};\n`
    );
    expect(applyLicenseHeader("'use server';\nexport {};\n", "agpl")).toBe(
      `${AGPL}\n\n'use server';\nexport {};\n`
    );
  });

  it("goes above @ts-nocheck, triple-slash references and biome-ignore", () => {
    const src =
      '// @ts-nocheck\n/// <reference types="node" />\n// biome-ignore-all lint/x: y\nexport {};\n';
    expect(applyLicenseHeader(src, "commercial")).toBe(
      `${COMMERCIAL}\n\n${src}`
    );
  });

  it("goes above Rust `//!` docs and `#![...]` attributes (not a shebang)", () => {
    const src = "//! Crate docs.\n#![deny(missing_docs)]\n\npub fn f() {}\n";
    expect(applyLicenseHeader(src, "agpl")).toBe(`${AGPL}\n\n${src}`);
    const attrFirst = "#![allow(dead_code)]\nfn f() {}\n";
    expect(applyLicenseHeader(attrFirst, "agpl")).toBe(
      `${AGPL}\n\n${attrFirst}`
    );
  });

  it("is idempotent", () => {
    for (const src of [
      "export {};\n",
      "#!/usr/bin/env node\nrun();\n",
      '"use client";\n',
      "//! docs\nfn f() {}\n",
      "no trailing newline",
      "a\r\nb\r\n",
      ""
    ]) {
      for (const kind of ["agpl", "commercial"] as const) {
        const once = applyLicenseHeader(src, kind);
        expect(applyLicenseHeader(once, kind), JSON.stringify(src)).toBe(once);
        expect(inspectLicenseHeader(once, kind)).toBe("ok");
      }
    }
  });

  it("replaces the other license's header (a file moved into packages/ee)", () => {
    const agpl = applyLicenseHeader("export const a = 1;\n", "agpl");
    expect(inspectLicenseHeader(agpl, "commercial")).toBe("wrong-license");
    const moved = applyLicenseHeader(agpl, "commercial");
    expect(moved).toBe(`${COMMERCIAL}\n\nexport const a = 1;\n`);
    expect(applyLicenseHeader(moved, "agpl")).toBe(agpl);
  });

  it("normalizes spacing and collapses a doubled header", () => {
    expect(applyLicenseHeader(`${AGPL}\nexport {};\n`, "agpl")).toBe(
      `${AGPL}\n\nexport {};\n`
    );
    expect(applyLicenseHeader(`${AGPL}\n\n\n\nexport {};\n`, "agpl")).toBe(
      `${AGPL}\n\nexport {};\n`
    );
    expect(
      applyLicenseHeader(`${COMMERCIAL}\n\n${AGPL}\n\nexport {};\n`, "agpl")
    ).toBe(`${AGPL}\n\nexport {};\n`);
    expect(inspectLicenseHeader(`${AGPL}\nexport {};\n`, "agpl")).toBe(
      "malformed"
    );
  });

  it("never strips the file's own comment that follows a header", () => {
    const src = `${AGPL}\n// What this module does.\n\nexport {};\n`;
    expect(applyLicenseHeader(src, "agpl")).toBe(
      `${AGPL}\n\n// What this module does.\n\nexport {};\n`
    );
  });

  it("preserves CRLF line endings and the (absent) trailing newline", () => {
    const crlf = "#!/usr/bin/env node\r\nimport a from 'a';\r\nrun(a);\r\n";
    const fixed = applyLicenseHeader(crlf, "agpl");
    expect(fixed).toBe(
      `#!/usr/bin/env node\r\n${LICENSE_HEADERS.agpl.join("\r\n")}\r\n\r\nimport a from 'a';\r\nrun(a);\r\n`
    );
    expect(fixed.replace(/\r\n/g, "")).not.toContain("\n");
    expect(applyLicenseHeader(fixed, "agpl")).toBe(fixed);
    expect(applyLicenseHeader(fixed, "commercial")).toBe(
      `#!/usr/bin/env node\r\n${LICENSE_HEADERS.commercial.join("\r\n")}\r\n\r\nimport a from 'a';\r\nrun(a);\r\n`
    );
    expect(applyLicenseHeader("export {}", "agpl")).toBe(
      `${AGPL}\n\nexport {}`
    );
  });

  it("keeps a byte-order mark first", () => {
    expect(applyLicenseHeader("﻿export {};\n", "agpl")).toBe(
      `﻿${AGPL}\n\nexport {};\n`
    );
  });

  it("leaves a file with a third-party notice untouched", () => {
    for (const src of [
      "// SPDX-License-Identifier: MIT\nexport {};\n",
      "/**\n * @license\n * Copyright 2024 Mozilla Foundation\n */\n",
      "// Copyright (c) 2019 Someone Else\nexport {};\n"
    ]) {
      expect(inspectLicenseHeader(src, "agpl")).toBe("foreign");
      expect(applyLicenseHeader(src, "agpl")).toBe(src);
    }
  });
});

describe("inspectLicenseHeader", () => {
  it("reports missing, ok and wrong-license", () => {
    expect(inspectLicenseHeader("export {};\n", "agpl")).toBe("missing");
    expect(inspectLicenseHeader(`${AGPL}\n\nexport {};\n`, "agpl")).toBe("ok");
    expect(inspectLicenseHeader(`${AGPL}\n\nexport {};\n`, "commercial")).toBe(
      "wrong-license"
    );
  });
});
