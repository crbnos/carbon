/**
 * Keys copied from `.env`, which `crbn up` loads into process.env before this
 * runs. A key with a `fallback` is always written. One without is left out when
 * unset: an empty line in `.env.local` would hide the `.env` value.
 */
const FROM_DOT_ENV: readonly { key: string; fallback?: string }[] = [
  // Consumed by docker-compose.dev.yml. Supabase's own services hold ~20
  // connections at idle, so the old default of 25 left no room for GoTrue/the
  // app and caused "remaining connection slots are reserved..." (53300)
  // errors that surfaced as random logouts. Matches the prod default.
  { key: "PG_MAX_CONNECTIONS", fallback: "100" },
  // The workflow integrations' Google OAuth app.
  { key: "GOOGLE_CLIENT_ID" },
  { key: "GOOGLE_CLIENT_SECRET" },
  { key: "GOOGLE_OAUTH_REDIRECT_URL" }
];

type EnvOptions = Parameters<typeof renderEnv>[0];

export function renderEnv(opts: {
  slug: string;
  ports: PortMap;
  redisDb: number;
  jwt: JwtCreds;
  /** The portless host prefix ("main" → erp.main.dev); null writes
   *  http://localhost:PORT URLs. */
  prefix: string | null;
  /**
   * Whether the assembler was selected to run. `ASSEMBLER_SERVICE_URL` IS the
   * pipeline's feature flag (`assemblerEnabled()` in @carbon/jobs) — writing it
   * with no service behind it turns clean job skips into dead-URL failures that
   * stamp model rows Failed. Omitted → written (migrate regenerates the env
   * without knowing the selection; only `up` passes false). A remote assembler
   * pinned in `.env` via `#force` wins regardless.
   */
  includeAssembler?: boolean;
  mode: StackMode;
  /** The database the apps use: the worktree's own in shared mode. */
  database: string;
}): string {
  const {
    slug,
    redisDb,
    jwt,
    prefix,
    includeAssembler = true,
    mode,
    database
  } = opts;
  const shared = mode === "shared";
  const portless = prefix !== null;
  const ports = stackPorts(opts.ports, mode);
  const hosts = stackHosts(mode, slug);
  const db = { port: ports.PORT_DB, database };

  const url = (name: RouteName) =>
    portless
      ? `https://${routeHost(name, prefix)}`
      : `http://localhost:${ports[ROUTES[name]]}`;
  const supabaseUrl = url("api");
  // The API URL Storage puts in resumable-upload URLs. A private Storage has
  // it as STORAGE_PUBLIC_URL; the shared one serves every worktree, so each
  // worktree's Envoy sends it (lds.template.yaml).
  const publicApi = new URL(supabaseUrl);
  const erpUrl = url("erp");

  const lines: string[] = [];
  lines.push("# Generated by crbn. Do not edit by hand.");
  lines.push("# Vite/React Router auto-load this file alongside .env;");
  lines.push("# values here override .env. The user's .env is left untouched.");
  lines.push("");
  lines.push(`CARBON_WORKTREE=${slug}`);
  if (portless) lines.push(`PORTLESS_TLD=${TLD}`);
  lines.push("");
  lines.push("# Internal compose ports (apps do not read these directly)");
  for (const [k, v] of Object.entries(ports)) lines.push(`${k}=${v}`);
  lines.push("");
  lines.push(
    shared
      ? "# Compose hosts: the shared containers (crbn-shared)"
      : "# Compose hosts: this worktree's private stack (--isolated)"
  );
  // Never a bare service name: the worktree's services also sit on
  // carbon-shared, where every worktree's (and crbn-shared's) "postgres",
  // "storage" and "inbucket" answer to it.
  lines.push(`DB_HOST=${hosts.db}`);
  lines.push(`DB_NAME=${database}`);
  // Realtime stays per worktree. Its replication slot names are unique per
  // cluster and Postgres caps them at 63 characters, so the suffix is a hash.
  lines.push(
    `SLOT_NAME_SUFFIX=${shared ? createHash("sha1").update(database).digest("hex").slice(0, 8) : ""}`
  );
  lines.push(`STORAGE_HOST=${hosts.storage}`);
  lines.push(`STORAGE_TENANT=${shared ? database : ISOLATED_STORAGE_TENANT}`);
  lines.push(`STORAGE_PUBLIC_HOST=${publicApi.host}`);
  lines.push(`STORAGE_PUBLIC_PROTO=${publicApi.protocol.replace(":", "")}`);
  lines.push(
    `STORAGE_PUBLIC_PORT=${publicApi.port || (publicApi.protocol === "https:" ? "443" : "80")}`
  );
  lines.push(`SMTP_HOST=${hosts.smtp}`);
  lines.push("");
  lines.push("# From .env, or crbn's default when it has one");
  for (const { key, fallback } of FROM_DOT_ENV) {
    const value = process.env[key] || fallback;
    if (value) lines.push(`${key}=${value}`);
  }
  lines.push("");
  lines.push(
    portless
      ? "# App-facing URLs (portless hostnames)"
      : "# App-facing URLs (localhost)"
  );
  lines.push(`DOMAIN=${portless ? `${prefix}.${TLD}` : "localhost"}`);
  lines.push(`ERP_URL=${erpUrl}`);
  lines.push(`MES_URL=${url("mes")}`);
  lines.push(`VERCEL_URL=${erpUrl}`);
  if (portless) lines.push(`GTM_URL=${erpUrl}`);
  lines.push("");
  lines.push(
    "# Supabase (per-worktree dev keys, minted from random JWT_SECRET)"
  );
  lines.push(`SUPABASE_URL=${supabaseUrl}`);
  lines.push(`SUPABASE_DB_URL=${dbUrl(db)}`);
  // The apps' pool goes through PgBouncer, as production's goes through
  // Supavisor. A borrowed stack from before the pooler has no port for it: an
  // empty value (read as unset) replaces a stale URL from an earlier render.
  lines.push(
    `SUPABASE_DB_POOLER_URL=${ports.PORT_POOLER ? dbUrl({ port: ports.PORT_POOLER, database }) : ""}`
  );
  lines.push("PGSSLMODE=disable");
  lines.push(`SUPABASE_JWT_SECRET=${jwt.secret}`);
  lines.push(`SUPABASE_ANON_KEY=${jwt.anonKey}`);
  lines.push(`SUPABASE_SERVICE_ROLE_KEY=${jwt.serviceKey}`);
  // The OAuth callback is the same for every worktree, so the redirect URI
  // is registered with Google and Azure once.
  const oauthBase = portless
    ? `https://${OAUTH_HOST}`
    : `http://localhost:${LOCALHOST_PORTS.PORT_API}`;
  lines.push(
    `SUPABASE_AUTH_EXTERNAL_GOOGLE_REDIRECT_URI=${oauthBase}/auth/v1/callback`
  );
  lines.push(
    `SUPABASE_AUTH_EXTERNAL_AZURE_REDIRECT_URI=${oauthBase}/auth/v1/callback`
  );
  lines.push("");
  lines.push(
    "# Integration OAuth callbacks on this stack's ERP host. Register the"
  );
  lines.push(
    "# URL on the provider's app, or pin your own in .env with #force."
  );
  lines.push(
    `ONSHAPE_V2_OAUTH_REDIRECT_URL=${erpUrl}/api/integrations/onshape-v2/oauth`
  );
  lines.push("");
  lines.push("# Aux services");
  lines.push(`REDIS_URL=redis://localhost:${SHARED_REDIS_PORT}/${redisDb}`);
  lines.push("INNGEST_DEV=1");
  lines.push(`INNGEST_BASE_URL=http://localhost:${ports.PORT_INNGEST}`);
  // SDK advertises this as its serve URL during self-register. Must be
  // reachable from inside the inngest container (handled via extra_hosts +
  // portless CA mount in docker-compose.dev.yml).
  lines.push(`INNGEST_SERVE_HOST=${erpUrl}`);
  // Hostname (no scheme) that docker-compose maps to host-gateway inside the
  // inngest container, so the SDK URL above resolves to the dev server on the
  // host. extra_hosts only accepts fully-qualified names — no wildcards —
  // which is why we can't reuse ${DOMAIN} (e.g. `main.dev` won't match the
  // `erp.main.dev` host the SDK URL points at).
  lines.push(
    `INNGEST_TLS_HOST=${portless ? routeHost("erp", prefix) : "localhost"}`
  );
  lines.push(`EMAIL_DEV_PORT=${ports.PORT_EMAIL}`);
  lines.push("");
  if (includeAssembler) {
    lines.push("# Assembler service (CAD conversion + motion planning)");
    lines.push(`ASSEMBLER_SERVICE_URL=${url("assembler")}`);
    lines.push("ASSEMBLER_SERVICE_API_KEY=dev-local-key");
  } else {
    lines.push("# Assembler not selected this run — URL omitted so the CAD");
    lines.push("# pipeline skips cleanly (assemblerEnabled() gates on it).");
  }
  lines.push("");
  lines.push("# Dev auth bypass");
  lines.push("DEV_BYPASS_EMAIL=test@carbon.ms");
  lines.push("");
  return lines.join("\n");
}

/**
 * The `#force` escape hatch: a line in the user-owned `.env` ending with a
 * `#force` comment pins that key — the generated `.env.local` omits it, so the
 * `.env` value wins even though `.env.local` normally overrides `.env` (Vite
 * load order). Survives regeneration by construction: the marker lives in
 * `.env`, which crbn never writes. e.g. point the local stack at a remote
 * assembler:  `ASSEMBLER_SERVICE_URL=https://xxx.execute-api.…  #force`
 */
const FORCE_MARKER = /#\s*force\s*$/i;
const ENV_KEY = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/;

function forcedKeys(dotEnvText: string): Set<string> {
  const keys = new Set<string>();
  for (const line of dotEnvText.split("\n")) {
    if (!FORCE_MARKER.test(line)) continue;
    const key = line.match(ENV_KEY)?.[1];
    if (key) keys.add(key);
  }
  return keys;
}

function omitForcedKeys(content: string, dotEnvText: string): string {
  const forced = forcedKeys(dotEnvText);
  if (forced.size === 0) return content;
  return content
    .split("\n")
    .map((line) => {
      const key = line.match(ENV_KEY)?.[1];
      return key && forced.has(key)
        ? `# ${key} omitted — #force'd in .env`
        : line;
    })
    .join("\n");
}

export function writeEnv(worktreeRoot: string, content: string) {
  const dotEnvPath = join(worktreeRoot, ".env");
  const dotEnv = existsSync(dotEnvPath) ? readFileSync(dotEnvPath, "utf8") : "";
  writeFileSync(
    join(worktreeRoot, ".env.local"),
    omitForcedKeys(content, dotEnv)
  );
}

/** Loads the worktree's env files into process.env: crbn's .env.local over
 *  the user's .env, the order the apps read them. Compose interpolates its
 *  files from process.env. `shellWins` keeps what the shell set (`up` and
 *  `reload` honour `CARBON_WORKTREE=foo crbn up`). */
export function loadEnvFiles(root: string, opts: { shellWins?: boolean } = {}) {
  loadDotenv({ path: join(root, ".env.local"), override: !opts.shellWins });
  loadDotenv({ path: join(root, ".env"), override: false });
}

/** Writes the worktree's .env.local and loads it into process.env. */
export function writeStackEnv(root: string, opts: EnvOptions) {
  writeEnv(root, renderEnv(opts));
  loadEnvFiles(root);
}
