import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { config as loadDotenv } from "dotenv";
import { join } from "pathe";
import {
  LOCALHOST_PORTS,
  OAUTH_HOST,
  ROUTES,
  type RouteName,
  routeHost,
  TLD
} from "./constants.js";
import { dbUrl } from "./stack.js";
import {
  ISOLATED_STORAGE_TENANT,
  SHARED_REDIS_PORT,
  type StackMode,
  stackHosts
} from "./topology.js";
